// Renders map marker PNGs into assets/markers and writes src/markerAssets.ts.
//   node assets/source/markers.js
// Origin markers: lettered circles (A..J) in the app's origin colours.
// Venue markers: numbered beer pins (1..20) matching the list ranking.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../..');
const { originColors } = { originColors: ['#2563EB', '#DB2777', '#059669', '#7C3AED', '#EA580C', '#0891B2', '#65A30D', '#9F1239'] };
const ORIGINS = 10, VENUES = 20;
const PIN = 'M54,136 C40,112 6,90 6,52 A48,48 0 1 1 102,52 C102,90 68,112 54,136 Z';

const originSvg = (i) => `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <circle cx="48" cy="48" r="40" fill="${originColors[i % originColors.length]}" stroke="#fff" stroke-width="8"/>
  <text x="48" y="49" text-anchor="middle" dominant-baseline="central" font-family="Inter,Arial,sans-serif" font-weight="800" font-size="40" fill="#fff">${String.fromCharCode(65 + i)}</text>
</svg>`;
const venueSvg = (n) => `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="140" viewBox="0 0 108 140">
  <defs><linearGradient id="b" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#FCD34D"/><stop offset="1" stop-color="#C2410C"/></linearGradient>
  <clipPath id="c"><path d="${PIN}"/></clipPath></defs>
  <path d="${PIN}" fill="url(#b)" stroke="#fff" stroke-width="6"/>
  <g clip-path="url(#c)"><path d="M0,0 H108 V26 C96,34 86,24 76,30 C66,36 58,26 48,31 C38,36 28,26 18,31 C10,35 4,30 0,32 Z" fill="#FFF8E7"/></g>
  <path d="${PIN}" fill="none" stroke="#fff" stroke-width="6"/>
  <text x="54" y="60" text-anchor="middle" dominant-baseline="central" font-family="Inter,Arial,sans-serif" font-weight="800" font-size="${n > 9 ? 36 : 42}" fill="#431407">${n}</text>
</svg>`;

(async () => {
  const b = await chromium.launch();
  const p = await b.newPage();
  const shoot = async (svg, file) => {
    await p.setContent(`<body style="margin:0">${svg}</body>`);
    await p.locator('svg').screenshot({ path: path.join(root, 'assets/markers', file), omitBackground: true });
  };
  for (let i = 0; i < ORIGINS; i++) await shoot(originSvg(i), `origin-${i}.png`);
  for (let n = 1; n <= VENUES; n++) await shoot(venueSvg(n), `venue-${n}.png`);
  await b.close();
  const list = (prefix, from, to) =>
    Array.from({ length: to - from + 1 }, (_, k) => `  require('../assets/markers/${prefix}-${from + k}.png'),`).join('\n');
  fs.writeFileSync(path.join(root, 'src/markerAssets.ts'), `// Generated by assets/source/markers.js — do not edit by hand.
/** Lettered circles for locations A, B, C... (same colours as the list). */
export const originMarkers: number[] = [
${list('origin', 0, ORIGINS - 1)}
];

/** Numbered beer pins for venues 1, 2, 3... (same order as the list). */
export const venueMarkers: number[] = [
${list('venue', 1, VENUES)}
];
`);
})();
